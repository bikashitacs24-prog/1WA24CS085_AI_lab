# Forward Chaining Algorithm

facts = {
    "American(Robert)",
    "Enemy(A,America)",
    "Owns(A,T1)",
    "Missile(T1)"
}

# Apply rules
if "Enemy(A,America)" in facts:
    facts.add("Hostile(A)")

if "Missile(T1)" in facts:
    facts.add("Weapon(T1)")

if "Missile(T1)" in facts and "Owns(A,T1)" in facts:
    facts.add("Sells(Robert,T1,A)")

# Main rule
if ("American(Robert)" in facts and
    "Weapon(T1)" in facts and
    "Sells(Robert,T1,A)" in facts and
    "Hostile(A)" in facts):
    facts.add("Criminal(Robert)")

# Display result
print("Knowledge Base:")
for f in facts:
    print(f)

if "Criminal(Robert)" in facts:
    print("\nRobert is a Criminal")
else:
    print("\nRobert is Not Proven Criminal")
