from itertools import product

def implies(a, b):
    return not a or b

def KB(p, q, r):
    return implies(q, p) and implies(p, not q) and (q or r)

def entails(query):
    for p, q, r in product([False, True], repeat=3):
        if KB(p, q, r) and not query(p, q, r):
            return False
    return True

while True:
    print("\n1. R")
