def unify(a, b):
    if a[0] != b[0] or len(a) != len(b):
        return "Failure"

    s = {}
    for x, y in zip(a[1:], b[1:]):
        if x == y:
            continue
        if x in s:
            x = s[x]
        if y in s:
            y = s[y]

        if len(x) == 1 and x.islower():
            s[x] = y
        elif len(y) == 1 and y.islower():
            s[y] = x
        else:
            return "Failure"

    return s


a = tuple(input("Enter first expression: ").replace("(", " ").replace(")", "").replace(",", " ").split())
b = tuple(input("Enter second expression: ").replace("(", " ").replace(")", "").replace(",", " ").split())

print("Substitution:", unify(a, b))
