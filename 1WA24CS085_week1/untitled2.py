# 2. TIC-TAC-TOE GAME

print("\n----- TIC TAC TOE GAME -----")

board = [' '] * 9

# Initial board positions
board[2], board[3], board[6] = 'X', 'X', 'X'
board[0], board[7], board[8] = 'O', 'O', 'O'

path_cost = {'X': 3, 'O': 3}
turn = 'X'

win_lines = [
    (0,1,2), (3,4,5), (6,7,8),
    (0,3,6), (1,4,7), (2,5,8),
    (0,4,8), (2,4,6)
]

while True:

    # Display board
    print("\n")
    print(f" {board[0]} | {board[1]} | {board[2]} ")
    print("-----------")
    print(f" {board[3]} | {board[4]} | {board[5]} ")
    print("-----------")
    print(f" {board[6]} | {board[7]} | {board[8]} ")

    print(f"Path Cost -> X: {path_cost['X']}, O: {path_cost['O']}")

    # Check winner
    winner = None

    for a, b, c in win_lines:
        if board[a] == board[b] == board[c] != ' ':
            winner = board[a]
            break

    if winner:
        print(f"\nPlayer {winner} wins!")
        print("Total Path Cost:", path_cost[winner])
        break

    elif ' ' not in board:
        print("\nIt's a tie!")
        break

    # Get player move
    try:
        move = int(input(f"\nPlayer {turn}, enter position (0-8): "))

        if move < 0 or move > 8 or board[move] != ' ':
            print("Invalid move! Try again.")
            continue

    except ValueError:
        print("Enter a valid number!")
        continue

    # Update board
    board[move] = turn
    path_cost[turn] += 1

    # Switch player
    turn = 'O' if turn == 'X' else 'X'


