import random

# Count attacking pairs of queens
def getConflicts(board, n):
    conflicts = 0

    for i in range(n):
        for j in range(i + 1, n):
            if board[i] == board[j] or abs(board[i] - board[j]) == abs(i - j):
                conflicts += 1

    return conflicts


# Main program
n = int(input("Enter the number of queens (N): "))

if n < 4:
    print("Enter a valid number greater than or equal to 4")

else:
    print("Searching for", n, "Queens solution using Hill Climbing...")

    while True:

        # Generate random board
        board = [random.randint(0, n - 1) for i in range(n)]

        current_conflicts = getConflicts(board, n)
        moved = True

        # Hill Climbing
        while moved:
            moved = False

            for col in range(n):
                original_row = board[col]

                for row in range(n):
                    if row == original_row:
                        continue

                    board[col] = row
                    new_conflicts = getConflicts(board, n)

                    if new_conflicts < current_conflicts:
                        current_conflicts = new_conflicts
                        moved = True
                        break

                if moved:
                    break

                board[col] = original_row

        # Check solution
        if current_conflicts == 0:
            print("\nSuccess! Solution found.")
            print("Queen row positions per column:", board)
            break

