import random
import math

n = int(input("Enter board size (N): "))

if n < 4:
    print("Enter N greater than or equal to 4")

else:
    while True:

        # Generate random starting board
        board = [random.randint(0, n-1) for i in range(n)]

        temp = 100.0

        while temp > 0.1:

            # Count current conflicts
            current_conflicts = 0

            for i in range(n):
                for j in range(i+1, n):
                    if board[i] == board[j] or abs(board[i]-board[j]) == abs(i-j):
                        current_conflicts += 1

            # Check solution
            if current_conflicts == 0:
                print("\nSuccess! Solution found:")
                print(board)
                print("BIKASHITA SAHA")
                print("USN: 1WA24CS085")
                exit()

            # Select random queen
            col = random.randint(0, n-1)
            old_row = board[col]

            board[col] = random.randint(0, n-1)

            # Count new conflicts
            new_conflicts = 0

            for i in range(n):
                for j in range(i+1, n):
                    if board[i] == board[j] or abs(board[i]-board[j]) == abs(i-j):
                        new_conflicts += 1

            delta = new_conflicts - current_conflicts

            # Accept or reject move
            if delta > 0:
                probability = math.exp(-delta / temp)
                random_chance = random.random()

                if random_chance >= probability:
                    board[col] = old_row

            # Reduce temperature
            temp *= 0.999

